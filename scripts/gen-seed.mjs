// Generate supabase/seed.sql from the app catalog so the demo and live backends agree.
// Run: node scripts/gen-seed.mjs   (Node 22.18+ strips the TypeScript types on import)
import { writeFileSync } from 'node:fs';

import { ITEMS, STALLS } from '../src/data/catalog.ts';

const q = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);

const stalls = STALLS.map((s, i) =>
  `  (${[s.id, s.name, s.tagline, s.location, s.avgPrepMin, s.maxActive, i].map(q).join(', ')})`).join(',\n');
const items = ITEMS.map((it, i) =>
  `  (${[it.id, it.stallId, it.name, it.description, it.category, it.price, it.photo, i].map(q).join(', ')})`).join(',\n');

writeFileSync('supabase/seed.sql', `-- Generated by scripts/gen-seed.mjs from src/data/catalog.ts. Do not edit by hand.
insert into public.stalls (id, name, tagline, location, avg_prep_min, max_active_orders, sort) values
${stalls}
on conflict (id) do update set name = excluded.name, tagline = excluded.tagline, location = excluded.location,
  avg_prep_min = excluded.avg_prep_min, sort = excluded.sort;

insert into public.menu_items (id, stall_id, name, description, category, price, photo, sort) values
${items}
on conflict (id) do update set name = excluded.name, description = excluded.description, category = excluded.category,
  price = excluded.price, photo = excluded.photo, sort = excluded.sort;
`);
console.log(`seed: ${STALLS.length} stalls, ${ITEMS.length} items`);
