// Pull Phosphor icons (MIT) from the Iconify API into src/ui/icon-data.ts.
// Run: node scripts/make-icons.mjs
import { writeFileSync } from 'node:fs';

const NAMES = `house-bold house-fill receipt-bold receipt-fill heart-bold heart-fill user-bold user-fill
magnifying-glass-bold shopping-bag-bold shopping-bag-fill arrow-left-bold arrow-right-bold arrow-up-right-bold
caret-right-bold caret-down-bold caret-up-bold x-bold plus-bold minus-bold clock-bold fire-bold fire-fill check-bold
check-circle-fill map-pin-bold phone-bold envelope-simple-bold graduation-cap-bold coffee-bold pizza-bold
hamburger-bold bowl-food-bold bowl-steam-bold cookie-bold cake-bold orange-slice-bold bread-bold sparkle-fill
star-fill bell-ringing-bold speaker-high-bold speaker-slash-bold vibrate-bold robot-bold storefront-bold
chef-hat-bold sign-out-bold info-bold qr-code-bold money-bold credit-card-bold device-mobile-bold bank-bold
note-pencil-bold trash-bold pause-fill play-fill lightning-fill hourglass-high-bold users-three-bold chart-bar-bold
gear-six-bold lock-simple-bold seal-check-fill arrows-clockwise-bold squares-four-bold copy-bold leaf-fill timer-bold
ticket-bold cooking-pot-bold warning-bold shield-check-bold hand-tap-bold image-bold confetti-bold
cup-bold ice-cream-bold flame-bold`.split(/\s+/).filter(Boolean);

const res = await fetch(`https://api.iconify.design/ph.json?icons=${NAMES.join(',')}`);
const json = await res.json();
const out = {};
const missing = [];
for (const n of NAMES) {
  const icon = json.icons?.[n];
  if (!icon) { missing.push(n); continue; }
  const paths = [...icon.body.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  out[n] = paths;
}
if (missing.length) console.log('missing:', missing.join(' '));
const body = Object.entries(out)
  .map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync('src/ui/icon-data.ts',
  `// Generated by scripts/make-icons.mjs from Phosphor Icons (MIT), viewBox 0 0 256 256.\n` +
  `export const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`);
console.log(Object.keys(out).length, 'icons written');
